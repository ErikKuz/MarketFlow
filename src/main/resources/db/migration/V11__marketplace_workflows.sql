);
CREATE INDEX idx_audit_order ON audit_events(order_id, created_at, id);
CREATE INDEX idx_audit_actor ON audit_events(actor_id, created_at DESC);
INSERT INTO audit_events(order_id, action, next_status, detail, created_at)
SELECT id, 'LEGACY_ORDER_IMPORTED', status, 'State before workflow migration', CURRENT_TIMESTAMP FROM orders;

CREATE TABLE seller_applications (
