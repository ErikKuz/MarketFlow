    status VARCHAR(30) NOT NULL CHECK (status IN ('PENDING','ACTIVE','REJECTED','BLOCKED')),
    reason VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, decided_at TIMESTAMP WITH TIME ZONE
);
INSERT INTO seller_applications(user_id, status, created_at, decided_at)
SELECT DISTINCT ur.user_id, 'ACTIVE', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM user_roles ur JOIN roles r ON r.id = ur.role_id WHERE r.name = 'SELLER';

