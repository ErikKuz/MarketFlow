UPDATE orders SET payment_expires_at = CURRENT_TIMESTAMP + INTERVAL '30 minutes'
WHERE status = 'CREATED' AND payment_status IN ('NOT_PAID', 'FAILED');
-- Do not retroactively open a new return window for historical completed orders.
UPDATE orders SET funds_released = TRUE WHERE status IN ('COMPLETED', 'CANCELLED');
CREATE INDEX idx_orders_expiry ON orders(status, payment_expires_at);
CREATE INDEX idx_orders_settlement ON orders(status, funds_released, return_deadline);

