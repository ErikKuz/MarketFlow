ALTER TABLE payment_transactions ADD CONSTRAINT chk_transaction_order
    CHECK (order_id IS NOT NULL OR type = 'WITHDRAWAL');

-- Protect historical income for still-open paid orders before withdrawals are enabled.
UPDATE payment_transactions p SET pending = TRUE
FROM orders o WHERE o.id = p.order_id AND o.payment_status = 'PAID'
AND o.status IN ('CONFIRMED', 'PROCESSING') AND p.status = 'COMPLETED'
AND p.type IN ('SELLER_PAYOUT', 'PLATFORM_COMMISSION');
UPDATE wallet_accounts w
SET pending_balance = held.amount, balance = w.balance - held.amount
FROM (SELECT user_id, SUM(amount) AS amount FROM payment_transactions WHERE pending = TRUE GROUP BY user_id) held
WHERE held.user_id = w.user_id;
-- A negative legacy balance aborts this entire migration instead of inventing money.

CREATE TABLE seller_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
    seller_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    total_amount NUMERIC(14,2) NOT NULL CHECK (total_amount > 0),
    status VARCHAR(30) NOT NULL CHECK (status IN ('NEW','ACCEPTED','PACKING','SHIPPED','DELIVERED','CANCELLED','RETURNED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    shipped_at TIMESTAMP WITH TIME ZONE,
    delivered_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_seller_order UNIQUE(order_id, seller_id)
);
CREATE INDEX idx_seller_orders_history ON seller_orders(seller_id, created_at DESC, id DESC);
INSERT INTO seller_orders(order_id, seller_id, total_amount, status, created_at, delivered_at)
SELECT o.id, oi.seller_id, SUM(oi.total_price),
    CASE WHEN o.payment_status = 'REFUNDED' AND o.status = 'COMPLETED' THEN 'RETURNED'
         WHEN o.status = 'CANCELLED' THEN 'CANCELLED'
         WHEN o.status = 'COMPLETED' THEN 'DELIVERED'
         WHEN o.status = 'PROCESSING' THEN 'PACKING' ELSE 'NEW' END,
    o.created_at, o.delivered_at
FROM orders o JOIN order_items oi ON oi.order_id = o.id
GROUP BY o.id, oi.seller_id, o.payment_status, o.status, o.created_at, o.delivered_at;

